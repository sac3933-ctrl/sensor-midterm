def mx(rows):
    n=len(rows[0])
    cells=''.join(f'<i>{c}</i>' for r in rows for c in r)
    return f'<span class="mx" style="grid-template-columns:repeat({n},auto)">{cells}</span>'
def fmt(v):
    return str(int(v)) if float(v).is_integer() else str(round(v,4))
def lsq_matrix(pts):
    xs=[p[0] for p in pts]; ys=[p[1] for p in pts]; N=len(pts)
    sx=sum(xs); sxx=sum(x*x for x in xs); sy=sum(ys); sxy=sum(x*y for x,y in pts)
    det=sxx*N-sx*sx
    na=N*sxy-sx*sy; nb=sxx*sy-sx*sxy
    a=na/det; b=nb/det
    X=mx([[x,1] for x in xs]); Y=mx([[y] for y in ys]); XT=mx([xs,[1]*N])
    XTX=mx([[sxx,sx],[sx,N]]); XTY=mx([[sxy],[sy]])
    inv=mx([[N,-sx],[-sx,sxx]]); num=mx([[fmt(na)],[fmt(nb)]]); ans=mx([[fmt(a)],[fmt(b)]])
    sq='² + '.join(map(str,xs))+'²'; pl=' + '.join(map(str,xs)); mul=' + '.join(f'{x}·{y}' for x,y in pts); ypl=' + '.join(map(str,ys))
    return (S('답안지에 쓰는 행렬방정식 풀이', P('교수님 풀이 형식이에요. 시험에서는 이 다섯 줄을 그대로 쓰면 돼요.')
      + E(f'① 식 세우기: Xp = y<br>X = {X},  p = {mx([["a"],["b"]])},  y = {Y}')
      + P('점마다 "a·x + b = y" 한 줄씩이라 X의 각 행이 [x, 1]이에요. 식은 ' + str(N) + '개, 미지수는 2개라 딱 맞는 답이 없어서 ②로 가요.')
      + E(f'② 양변에 Xᵀ 곱하기: XᵀXp = Xᵀy<br>Xᵀ = {XT}')
      + E(f'③ XᵀX = {mx([[sq, pl],[pl, N]])} = {XTX}<br>Xᵀy = {mx([[mul],[ypl]])} = {XTY}')
      + P('XᵀX는 항상 [[Σx², Σx], [Σx, N]], Xᵀy는 [[Σxy], [Σy]]예요. 1단계 표의 합계가 그대로 들어가요.')
      + E(f'④ 역행렬: det = {sxx}×{N} − {sx}×{sx} = {det}<br>(XᵀX)⁻¹ = (1/{det}) × {inv}')
      + P('2×2 역행렬: 대각선 두 수는 자리를 바꾸고, 나머지 두 수는 부호만 바꾼 뒤 det로 나눠요.')
      + E(f'⑤ p = (XᵀX)⁻¹Xᵀy = (1/{det}) × {inv} × {XTY}<br>= (1/{det}) × {num} = {ans}')
      + P(f'∴ <b>a = {fmt(a)}, b = {fmt(b)} → y = {fmt(a)}x {"−" if b<0 else "+"} {fmt(abs(b))}</b>')
      + C('행렬 곱: 윗줄 = ' + f'{N}×{sxy} + ({-sx})×{sy} = {fmt(na)}, 아랫줄 = ({-sx})×{sxy} + {sxx}×{sy} = {fmt(nb)}. 왼쪽 행렬의 가로줄과 오른쪽 세로줄을 짝지어 곱해 더해요.')
      ))
